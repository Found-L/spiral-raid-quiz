def add(section, role, kind, at, prompt, correct, wrong, explanation):
    assert correct and wrong and (kind == 'multiple' or len(correct) == 1)
    options = [(text, True) for text in correct] + [(text, False) for text in wrong]
    if kind != 'judge':
        rng.shuffle(options)
    values = [{'id': chr(97 + i), 'text': text} for i, (text, _) in enumerate(options)]
    questions.append({
        'id': f'q{len(questions)+1:03}', 'section': section, 'role': role, 'type': kind,
        'question': prompt, 'options': values,
        'answer': [values[i]['id'] for i, (_, yes) in enumerate(options) if yes],
        'explanation': explanation,
        'source': f'巅峰服视频 {at//60:02d}:{at%60:02d}',
        'sourceUrl': videos[section] + f'?t={at}',
    })

def one(s, role, at, q, a, b, why): add(s, role, 'single', at, q, [a], b, why)
def many(s, role, at, q, a, b, why): add(s, role, 'multiple', at, q, a, b, why)
def judge(s, role, at, q, answer, why):
    add(s, role, 'judge', at, q, ['正确' if answer else '错误'], ['错误' if answer else '正确'], why)
    # Keep the familiar 正确 / 错误 ordering even for a false statement.
    question = questions[-1]
    if not answer:
        question['options'] = [{'id':'a','text':'正确'},{'id':'b','text':'错误'}]
        question['answer'] = ['b']
def fill(s, role, at, q, a, b, why): add(s, role, 'fill', at, q, [a], b, why)

